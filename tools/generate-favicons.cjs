#!/usr/bin/env node
/**
 * Every small icon, generated from public/favicon.svg.
 *
 * This exists because the site shipped TWO different favicons. favicon.ico
 * carried the full LeafSeal — leaf inside a ring — and favicon.svg carried a
 * bare leaf with no ring. Chrome and Firefox prefer the SVG, Safari and older
 * browsers take the .ico, so which mark you saw depended on your browser, and
 * nothing in the repo could notice because the two files were drawn by hand at
 * different times. That is the same drift this repo keeps catching in prose,
 * except in binary, where nobody reads the diff.
 *
 * So the .ico and the PNGs are now OUTPUT, not sources. There is one drawing.
 *
 * It also emits mask-icon.svg for Safari pinned tabs, which has a real
 * constraint the old markup ignored: a mask icon must be a MONOCHROME shape on
 * a TRANSPARENT background, because Safari fills it with the `color` given on
 * the <link>. Pointing mask-icon at a full-colour SVG with an opaque black
 * <rect> — which is what this site did — hands Safari a rectangle to fill, and
 * the pinned tab renders as a solid block.
 *
 * Run: node tools/generate-favicons.cjs
 * Not in the build. Icons change about once a year, and the build should not
 * rasterise images on every deploy to produce bytes that never change. There
 * is a check in tools/check-icons.cjs that fails the build if the outputs stop
 * matching the source, which is the part that actually needs to be automatic.
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const PUBLIC = 'public';
const SRC = path.join(PUBLIC, 'favicon.svg');

// 16 and 32 are the tab. 48 is the Windows taskbar and the Chrome bookmark
// bar's retina step. Nothing larger belongs in an .ico: apple-touch-icon and
// the 192/512 manifest icons carry the full seal and are drawn separately.
const ICO_SIZES = [16, 32, 48];

/**
 * ICO is a 6-byte header, then one 16-byte directory entry per image, then the
 * payloads. Every modern browser accepts PNG payloads, which is what this
 * writes — it keeps each frame exactly as sharp rendered it rather than
 * round-tripping through BMP and losing the alpha edge.
 */
function buildIco(frames) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // 1 = icon
  header.writeUInt16LE(frames.length, 4);

  const dir = Buffer.alloc(16 * frames.length);
  let offset = header.length + dir.length;

  frames.forEach((f, i) => {
    const o = i * 16;
    // 256 is written as 0 in this field; we never go that big, but be correct.
    dir.writeUInt8(f.size >= 256 ? 0 : f.size, o);
    dir.writeUInt8(f.size >= 256 ? 0 : f.size, o + 1);
    dir.writeUInt8(0, o + 2); // palette colours: 0 = not paletted
    dir.writeUInt8(0, o + 3); // reserved
    dir.writeUInt16LE(1, o + 4); // colour planes
    dir.writeUInt16LE(32, o + 6); // bits per pixel
    dir.writeUInt32LE(f.data.length, o + 8);
    dir.writeUInt32LE(offset, o + 12);
    offset += f.data.length;
  });

  return Buffer.concat([header, dir, ...frames.map((f) => f.data)]);
}

(async () => {
  if (!fs.existsSync(SRC)) {
    console.error(`generate-favicons: ${SRC} not found`);
    process.exit(1);
  }
  const svg = fs.readFileSync(SRC);

  const frames = [];
  for (const size of ICO_SIZES) {
    // density is what makes a vector downscale cleanly instead of rendering at
    // 96dpi and then being squashed; without it the 16px frame is mush.
    const data = await sharp(svg, { density: 512 })
      .resize(size, size, { fit: 'contain' })
      .png({ compressionLevel: 9 })
      .toBuffer();
    frames.push({ size, data });
    if (size === 16 || size === 32) {
      fs.writeFileSync(path.join(PUBLIC, `favicon-${size}.png`), data);
    }
  }

  fs.writeFileSync(path.join(PUBLIC, 'favicon.ico'), buildIco(frames));

  // Safari pinned tab: one path, no fill colour, no background. Safari applies
  // the colour from <link rel="mask-icon" color="…">.
  const leaf = svg.toString().match(/<path[^>]*\sd="([^"]+)"/);
  if (!leaf) {
    console.error('generate-favicons: no <path d="…"> in favicon.svg — cannot build the mask icon');
    process.exit(1);
  }
  fs.writeFileSync(
    path.join(PUBLIC, 'mask-icon.svg'),
    `<!-- Generated by tools/generate-favicons.cjs from favicon.svg. Monochrome,\n` +
      `     transparent: Safari fills this shape with the colour on the <link>. -->\n` +
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">\n` +
      `  <path d="${leaf[1]}"/>\n` +
      `</svg>\n`,
  );

  const sizes = ICO_SIZES.join('/');
  console.log(
    `generate-favicons: favicon.ico (${sizes}), favicon-16.png, favicon-32.png, mask-icon.svg — all from ${SRC}`,
  );
})();
